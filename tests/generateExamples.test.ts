// Writes the `examples/` folder: one TUI Studio project and its export for every framework.
// Not a real test: it only runs with `npm run examples` (GENERATE_EXAMPLES=1).

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { describe, it } from 'vitest';
import { exportToFiles } from '../src/utils/export/codeExporter';
import { apiDesign } from './fixtures/apiDesign';

const OUT = resolve(__dirname, '..', 'examples', 'demo');

const FRAMEWORKS: { id: string; label: string; needs: string; steps: string[] }[] = [
  {
    id: 'textual',
    label: 'Textual (Python)',
    needs: 'Python 3.9+',
    steps: ['pip install "textual>=6"', 'python ui.py'],
  },
  {
    id: 'ink',
    label: 'Ink (React)',
    needs: 'Node.js 20+',
    steps: ['npm install', 'npm start'],
  },
  {
    id: 'opentui',
    label: 'OpenTUI (React)',
    needs: 'Bun 1.2+',
    steps: ['bun install', 'bun start'],
  },
  {
    id: 'blessed',
    label: 'Blessed (Node.js)',
    needs: 'Node.js 18+',
    steps: ['npm install', 'npm start'],
  },
  {
    id: 'bubbletea',
    label: 'Bubble Tea (Go)',
    needs: 'Go 1.24+',
    steps: ['go mod tidy', 'go run .'],
  },
  {
    id: 'tview',
    label: 'tview (Go)',
    needs: 'Go 1.23+',
    steps: ['go mod tidy', 'go run .'],
  },
  {
    id: 'ratatui',
    label: 'Ratatui (Rust)',
    needs: 'Rust (cargo)',
    steps: ['cargo run'],
  },
];

const KEYS =
  'Keys: `Tab` / `Shift+Tab` move the focus, `Enter` or `Space` activates, `Ctrl+L` shows the log, ' +
  '`q` or `Ctrl+C` quits (not while a text field has focus). Mouse: click, wheel and ' +
  'PageUp/PageDown/Home/End scroll. Node-based apps (Ink, Blessed, OpenTUI) receive mouse input ' +
  'only in terminals that send VT mouse reports, such as Windows Terminal or VS Code; the classic ' +
  'console window (conhost) delivers none to Node, so use the keyboard there.';

function readme(f: (typeof FRAMEWORKS)[number]): string {
  return `# Demo: ${f.label}

Generated by TUI Studio from [\`../demo.tui\`](../demo.tui). Requires ${f.needs}.

\`\`\`bash
${f.steps.join('\n')}
\`\`\`

${KEYS}

The program API (named components, states, events, error dialog) is described in
\`docs/PROGRAM_API.md\`. Components with a code name (\`status\`, \`name_input\`, \`submit_btn\`,
\`agree\`, \`color\`, \`progress\`, \`results\`, \`files\`, \`pages\`, \`panel\`, \`confirm\`) are reachable
from your program; look for \`program\` in the main file for the place to start.
`;
}

describe.skipIf(!process.env.GENERATE_EXAMPLES)('generate examples', () => {
  it('writes examples/demo', () => {
    try {
      rmSync(OUT, { recursive: true, force: true });
    } catch {
      // A terminal open inside the folder locks it: the files are overwritten instead.
    }
    const root = apiDesign();
    root.name = 'Demo';

    const write = (path: string, content: string) => {
      const file = join(OUT, path);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content, 'utf8');
    };

    write(
      'demo.tui',
      JSON.stringify(
        {
          version: '2',
          meta: { name: 'Demo', theme: 'dracula', activeScreen: 'screen-1' },
          screens: [{ id: 'screen-1', tree: root }],
        },
        null,
        2
      ) + '\n'
    );

    for (const f of FRAMEWORKS) {
      for (const file of exportToFiles(root, f.id, [{ id: 'screen-1', root }])) {
        write(join(f.id, file.path), file.content);
      }
      write(join(f.id, 'README.md'), readme(f));
    }

    const rows = FRAMEWORKS.map(
      (f) => `| ${f.label} | \`${f.id}/\` | ${f.needs} | \`${f.steps.join(' && ')}\` |`
    ).join('\n');
    write(
      'README.md',
      `# Demo project

\`demo.tui\` is a TUI Studio project (open it in the editor with *File → Open*). The folders next to
it are its export for every framework; each is a complete, runnable project.

| Framework | Folder | Needs | Start (inside the folder) |
| --- | --- | --- | --- |
${rows}

${KEYS}

Regenerate everything after changing the design or an exporter: \`npm run examples\`.
`
    );
  });
});
